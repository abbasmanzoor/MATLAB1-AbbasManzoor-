% Question 2: Primary data and secondary data
% This program prints the difference and the two methods of collecting primary data.

clc; clear;

disp('--- Primary data ---');
disp('Collected first-hand by the researcher for his own study (e.g. own survey).');
disp(' ');
disp('--- Secondary data ---');
disp('Already collected by someone else (e.g. government report, newspaper, website).');
disp(' ');

disp('--- Two methods of collecting primary data ---');
disp('1) Personal interview : the investigator asks the questions face to face.');
disp('2) Questionnaire      : written questions are given to people to fill in.');
disp(' ');

disp('--- Questionnaire method ---');
disp('Advantage    : a large number of people can be reached cheaply and quickly.');
disp('Disadvantage : many people do not return it, and some may misunderstand the questions.');
